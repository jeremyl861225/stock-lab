def build(horizon: int, vol: dict) -> dict:
    out = []
    for code, p20, skew, conf, why in J:
        p = 0.5 + (p20 - 0.5) * math.sqrt(horizon / 20)
        base = 0.85 * vol.get(code, 0.02) * math.sqrt(horizon)
        up, dn = base * (1 + skew), -base * (1 - skew)
        ev = p * up + (1 - p) * dn
        sig = vol.get(code, 0.02) * math.sqrt(horizon)
        q10, q90 = quantiles(ev, sig)
        ratio = abs(up / dn) if dn else float("inf")
        tag = "正偏（上檔大）" if ratio > 1.25 else ("負偏（下檔大）" if ratio < 0.8 else "對稱")
        out.append({
            "code": code, "stance": "bullish" if ev >= 0 else "bearish",
            "conviction": conf, "prob_up": round(p, 3), "exp_ret": round(ev, 5),
            "ret_q10": round(q10, 5), "ret_q90": round(q90, 5),
            "up_magnitude": round(up, 4), "dn_magnitude": round(dn, 4),
            "reward_risk": round(ratio, 2), "asymmetry": tag,
            "thesis": why, "inference": why,
            "facts": ["當日四面向資料見 data/briefing.parquet（as_of 20260917）",
                      "乙烯 1,150 美元/噸（週漲 4.1%）、丙烯 1,225（+2.1%）——經濟日報 9/17",
                      "CPO 降規為法人傳言，台光電／聯茂／台燿當日公開駁斥——工商時報 9/17",
                      "大盤 +439 點收 46,000 之上，量 8,100 億"],
            "falsifier":
                "若 CCL 三檔在大廠駁斥後仍續跌逾 10%，代表市場認定降規為真、"
                "『傳言已被駁斥』的立論失效；"
                "若金融股在 RSI 78+ 且融資暴增的位置續漲逾 5%，『籌碼擁擠』判讀失效；"
                "若乙烯或丙烯報價轉跌，塑化的實價支撐消失；"
                "若南亞科外資轉為連續賣超，『基本面背離終將收斂』失效。",
        })
    return {"as_of": "20260917", "horizon": horizon, "analyst": "claude-opus-5",
            "version": "v1", "market_context": MACRO, "judgments": out}


