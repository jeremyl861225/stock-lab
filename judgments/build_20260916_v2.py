def build(horizon: int, vol: dict) -> dict:
    out = []
    scale = math.sqrt(horizon)
    for code, p20, skew, conf, why in J:
        # 漂移 ∝ h、波動 ∝ √h ⇒ (p−0.5) ∝ √h，故 p5 的偏離是 p20 的 √(5/20)=0.5 倍
        p = 0.5 + (p20 - 0.5) * math.sqrt(horizon / 20)
        base = 0.8 * vol.get(code, 0.02) * scale      # 幅度隨各股波動度縮放
        up = base * (1 + skew)
        dn = -base * (1 - skew)
        ev = p * up + (1 - p) * dn
        ratio = abs(up / dn) if dn else float("inf")
        tag = "正偏（上檔大）" if ratio > 1.25 else ("負偏（下檔大）" if ratio < 0.8 else "對稱")
        w = why
        if horizon == 5 and "法說會在期間內" in w:
            w = w.replace("、10月中法說會在期間內", "（10月中法說會不在5日視窗內）")
        out.append({
            "code": code, "stance": "bullish" if ev >= 0 else "bearish",
            "conviction": conf, "prob_up": round(p, 3),
            "exp_ret": round(ev, 5),
            "ret_q10": round(dn * 1.6, 5), "ret_q90": round(up * 1.6, 5),
            "up_magnitude": round(up, 4), "dn_magnitude": round(dn, 4),
            "reward_risk": round(ratio, 2), "asymmetry": tag,
            "thesis": w, "facts": ["四面向資料見 data/briefing.parquet"],
            "inference": w,
            "falsifier": "若金融股在 RSI 76+ 的位置續漲逾 5%，或記憶體雙雄外資再度轉為連續賣超，"
                         "則『超買回歸』與『基本面背離終將收斂』兩個前提分別失效。",
        })
    return {"as_of": "20260916", "horizon": horizon, "analyst": "claude-opus-5",
            "version": "v2", "market_context": MACRO, "judgments": out}


