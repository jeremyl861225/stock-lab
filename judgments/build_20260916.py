def to_judgments(rows, horizon):
    out = []
    for code, p, up, dn, conf, why in rows:
        ev = p*up + (1-p)*dn
        q10, q90 = dn*1.35, up*1.35          # 尾端比核心情境再寬 35%
        if ev < q10: q10 = ev - abs(dn)*0.5
        if ev > q90: q90 = ev + abs(up)*0.5
        ratio = abs(up/dn) if dn else float('inf')
        tag = "正偏（上檔大）" if ratio > 1.25 else ("負偏（下檔大）" if ratio < 0.8 else "對稱")
        out.append({
            "code": code, "stance": "bullish" if ev >= 0 else "bearish",
            "conviction": conf, "prob_up": round(p, 3),
            "exp_ret": round(ev, 5), "ret_q10": round(q10, 5), "ret_q90": round(q90, 5),
            "up_magnitude": round(up, 4), "dn_magnitude": round(dn, 4),
            "reward_risk": round(ratio, 2), "asymmetry": tag,
            "thesis": why,
            "facts": ["見 data/briefing.parquet 之四面向欄位（基本面 PER/PBR/殖利率/營收YoY、"
                      "籌碼 外資/投信/融資、技術 RSI/動能/距高點、新聞 12 則）"],
            "inference": why,
            "falsifier": "若外資由連續賣超轉為連續買超且成交量放大，"
                         "「防禦性撤退」的前提即不成立，金融股看空與科技股看多兩邊都會錯。",
        })
    return {"as_of": "20260916", "horizon": horizon, "analyst": "claude-opus-5",
            "market_context": MACRO, "judgments": out}

