    b = pd.read_parquet("data/briefing.parquet")
    b = b[b["market"] == "US"]
    vol = dict(zip(b["code"], b["vol_20"].fillna(0.02)))
    miss = [c for c, *_ in J if c not in vol]
    extra = set(vol) - {c for c, *_ in J}
    assert not miss, f"代號不在 universe：{miss}"
    assert not extra, f"universe 有檔位未判斷：{extra}"
    for h in (20, 5):
        d = build(h, vol)
